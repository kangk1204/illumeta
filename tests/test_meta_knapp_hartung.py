# Two-sided t critical values at alpha = 0.05, from published tables. These pin the
# hand-written regularized incomplete beta independently of metafor: if the continued
# fraction were subtly wrong, agreeing with metafor on 24 CpGs and with the textbook
# here would both have to fail in the same direction.
T_CRITICAL_005 = [
    (1, 12.70620473617469),
    (2, 4.302652729911275),
    (3, 3.182446305284263),
    (4, 2.776445105198305),
    (10, 2.228138851986273),
    (100, 1.983971518523537),
]


def _pad(effects: list[float], ses: list[float]) -> tuple[list[float], list[float], list[bool]]:
    """Pad a k-cohort case out to the 4-slot layout _random_effect_meta_one expects."""
    valid = [True] * len(effects) + [False] * (4 - len(effects))
    return (
        effects + [math.nan] * (4 - len(effects)),
        ses + [math.nan] * (4 - len(ses)),
        valid,
    )


class TDistributionTests(unittest.TestCase):
    def test_matches_published_critical_values(self):
        for df, t in T_CRITICAL_005:
            with self.subTest(df=df):
                self.assertAlmostEqual(_t_two_sided_p(t, df), 0.05, places=10)

    def test_degenerate_inputs(self):
        self.assertEqual(_t_two_sided_p(0.0, 3), 1.0)
        self.assertEqual(_t_two_sided_p(float("inf"), 3), 0.0)
        self.assertEqual(_t_two_sided_p(float("-inf"), 3), 0.0)
        self.assertTrue(math.isnan(_t_two_sided_p(float("nan"), 3)))
        self.assertTrue(math.isnan(_t_two_sided_p(1.0, 0)))

    def test_is_heavier_tailed_than_the_normal(self):
        # The whole point of the adjustment: at the same statistic the t reference must
        # give a larger P-value, and the gap must shrink as df grows.
        from illumeta_meta import _normal_two_sided_p

        previous_gap = None
        for df in (1, 2, 4, 30, 200):
            gap = _t_two_sided_p(2.5, df) - _normal_two_sided_p(2.5)
            self.assertGreater(gap, 0.0, df)
            if previous_gap is not None:
                self.assertLess(gap, previous_gap, df)
            previous_gap = gap


class KnappHartungAgreesWithMetaforTests(unittest.TestCase):
    def test_frozen_cases(self):
        for index, (effects, ses, ref_se, ref_p) in enumerate(CASES):
            with self.subTest(case=index, k=len(effects)):
                res = _random_effect_meta_one(*_pad(list(effects), list(ses)))
                self.assertAlmostEqual(
                    res["random_se_hk"], ref_se, delta=abs(ref_se) * 1e-9
                )
                self.assertAlmostEqual(res["random_p_hk"], ref_p, delta=abs(ref_p) * 1e-9)

    def test_every_stratum_is_covered(self):
        # Guards the generator, not the estimator: a regenerated CASES list that
        # silently lost the tau2 == 0 branch would still pass every assertion above.
        ks = {len(effects) for effects, _ses, _se, _p in CASES}
        self.assertEqual(ks, {2, 3, 4})
        zero_tau2 = 0
        for effects, ses, _se, _p in CASES:
            if _random_effect_meta_one(*_pad(list(effects), list(ses)))["tau2"] == 0.0:
                zero_tau2 += 1
        self.assertGreater(zero_tau2, 0)
        self.assertLess(zero_tau2, len(CASES))


class KnappHartungIsContainedTests(unittest.TestCase):
    def test_pooled_estimate_is_untouched(self):
        for effects, ses, _se, _p in CASES:
            padded = _pad(list(effects), list(ses))
            res = _random_effect_meta_one(*padded)
            # Recomputing the DL pooled effect the long way: if the adjustment had been
            # folded into the weights, these would disagree.
            weights = [
                1.0 / (se * se + res["tau2"])
                for se, ok in zip(padded[1], padded[2])
                if ok
            ]
            expected = sum(
                w * e for w, e in zip(weights, [x for x, ok in zip(padded[0], padded[2]) if ok])
            ) / sum(weights)
            self.assertAlmostEqual(res["random_effect"], expected, delta=abs(expected) * 1e-12)

    def test_normal_reference_columns_survive_the_adjustment(self):
        for effects, ses, _se, _p in CASES:
            res = _random_effect_meta_one(*_pad(list(effects), list(ses)))
            self.assertTrue(math.isfinite(res["random_se"]))
            self.assertTrue(math.isfinite(res["random_p"]))

    def test_at_two_cohorts_only_the_reference_distribution_changes(self):
        """With k = 2 the adjusted standard error equals the unadjusted one exactly.

        This is algebra, not coincidence. For k = 2 the DerSimonian-Laird estimate makes
        the re-weighted dispersion sum equal 1, and the Knapp-Hartung variance is that
        sum divided by df = 1 times the random-effects variance. metafor shows the same
        identity. So at k = 2 the entire effect of the adjustment is the switch from the
        normal to t(1) -- which is severe, because t(1) is Cauchy. Pinned because a
        future reader comparing the two columns will otherwise conclude the flag is
        broken.
        """
        two_cohort = [case for case in CASES if len(case[0]) == 2]
        self.assertGreater(len(two_cohort), 0)
        for effects, ses, _se, _p in two_cohort:
            res = _random_effect_meta_one(*_pad(list(effects), list(ses)))
            if res["tau2"] == 0.0:
                continue  # tau2 truncated: the identity is derived for a positive tau2
            self.assertAlmostEqual(
                res["random_se_hk"], res["random_se"], delta=res["random_se"] * 1e-12
            )
            self.assertGreater(res["random_p_hk"], res["random_p"])

    def test_adjusted_p_is_not_uniformly_larger_but_is_usually_so(self):
        # Knapp-Hartung is not a monotone inflation: when the studies agree more closely
        # than their standard errors imply, it can shrink the SE. Asserting "always
        # larger" would encode a false property that a future refactor could "fix".
        larger = sum(
            1
            for effects, ses, _se, _p in CASES
            if (res := _random_effect_meta_one(*_pad(list(effects), list(ses))))["random_p_hk"]
            > res["random_p"]
        )
        self.assertGreater(larger, len(CASES) // 2)

    def test_output_columns_appear_only_when_requested(self):
        default = _base_fieldnames(["a", "b"])
        for column in ("random_se_hk", "random_p_hk", "random_fdr_hk"):
            self.assertNotIn(column, default)

        requested = _base_fieldnames(["a", "b"], report_knapp_hartung=True)
        for column in ("random_se_hk", "random_p_hk", "random_fdr_hk"):
            self.assertIn(column, requested)

        # Added, not reordered. Stated as an exact identity rather than a prefix slice,
        # because the columns land before the per-cohort block and a slice comparison
        # can pass while the tail has silently shifted.
        hk = {"random_se_hk", "random_p_hk", "random_fdr_hk"}
        self.assertEqual([c for c in requested if c not in hk], default)
        self.assertEqual(len(requested), len(default) + 3)


class DegenerateInputTests(unittest.TestCase):
    def test_single_cohort_has_no_adjustment(self):
        res = _random_effect_meta_one([0.1, math.nan], [0.05, math.nan], [True, False])
        self.assertEqual(res["k"], 1)
        self.assertTrue(math.isnan(res["random_se_hk"]))
        self.assertTrue(math.isnan(res["random_p_hk"]))

    def test_no_usable_cohort_returns_nan(self):
        res = _random_effect_meta_one([math.nan] * 2, [math.nan] * 2, [False, False])
        self.assertTrue(math.isnan(res["random_se_hk"]))
        self.assertTrue(math.isnan(res["random_p_hk"]))

    def test_identical_effects_are_refused_rather_than_reported(self):
        """Cohorts reporting the same effect must not become the top hit in the run.

        The Knapp-Hartung variance is estimated from the dispersion of the study effects
        about the pooled value. When that dispersion is zero the variance is zero and the
        t statistic diverges: metafor returns se = 0 and P = 0 exactly, and an unguarded
        implementation returns whatever floating-point residue survived the cancellation
        -- here about 3e-17, which would rank ahead of every real finding. Over hundreds
        of thousands of CpGs run unattended that is a trap, so this case is reported as
        NaN. The normal-reference columns are unaffected and still carry a usable answer.
        """
        res = _random_effect_meta_one([0.2, 0.2, math.nan, math.nan],
                                      [0.05, 0.05, math.nan, math.nan],
                                      [True, True, False, False])
        self.assertEqual(res["k"], 2)
        self.assertTrue(math.isnan(res["random_se_hk"]))
        self.assertTrue(math.isnan(res["random_p_hk"]))
        self.assertTrue(math.isfinite(res["random_se"]))
        self.assertTrue(math.isfinite(res["random_p"]))

    def test_the_guard_does_not_fire_on_merely_close_agreement(self):
        # The guard must catch annihilation, not concordance. Cohorts that agree closely
        # are exactly what the adjustment is supposed to reward with a small SE.
        res = _random_effect_meta_one([0.2, 0.2001, math.nan, math.nan],
                                      [0.05, 0.05, math.nan, math.nan],
                                      [True, True, False, False])
        self.assertTrue(math.isfinite(res["random_se_hk"]))
        self.assertTrue(math.isfinite(res["random_p_hk"]))


