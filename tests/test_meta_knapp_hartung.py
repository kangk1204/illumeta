"""Knapp-Hartung adjustment: agreement with metafor, and containment of its effects.

Two things are pinned here. The first is arithmetic: the adjusted standard error and
t-referred P-value must match metafor's rma(test="knha") on frozen cases. CI has no R,
so metafor's outputs are frozen below rather than recomputed; they were generated by
script from metafor's own output, so no value was transcribed by hand.

The second is containment, and it is the reason this file is longer than the first test.
The adjustment is offered as a sensitivity, not as a new default, so it must not touch
the pooled estimate, the existing columns, or what counts as a core candidate. A change
that silently made Knapp-Hartung the default would move every candidate count a user
has already published, while every test that only checked arithmetic kept passing.
"""

